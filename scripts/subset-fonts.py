#!/usr/bin/env python3
"""Subset OPPO Sans 4.0 (variable, wght 100-700) into two self-hosted woff2 files.

1. oppo-sans-site.woff2   - every non-ASCII character actually used in src/ + data/ (small, preloaded)
2. oppo-sans-common-NN.woff2 - remaining GB2312 hanzi + CJK punctuation, sliced into ~400-char
                            chunks and fetched lazily via unicode-range (what readers type into bottles)

Writes src/styles/fonts.css with matching @font-face rules.
Source TTF path: ../fonts/OPPOSans4.0.ttf (outside the app; never shipped).
"""
import pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_TTF = ROOT.parent / "fonts" / "OPPOSans4.0.ttf"
OUT = ROOT / "public" / "fonts"
CSS = ROOT / "src" / "styles" / "fonts.css"

def used_chars():
    chars = set()
    for p in list((ROOT / "src").rglob("*")) + list((ROOT / "data").rglob("*")):
        if p.is_file() and p.suffix in {".astro", ".mdx", ".md", ".ts", ".tsx", ".css", ".json"}:
            chars.update(p.read_text(encoding="utf-8"))
    return {c for c in chars if ord(c) > 0x7F}

def gb2312():
    out = set()
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                out.add(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return out

def ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], None, None
    for c in cps:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev)); start = prev = c
    if start is not None:
        out.append((start, prev))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in out)

def subset(chars, name):
    txt = OUT / f"{name}.txt"
    txt.write_text("".join(sorted(chars)), encoding="utf-8")
    subprocess.run([sys.executable, "-m", "fontTools.subset", str(SRC_TTF),
                    f"--text-file={txt}", "--flavor=woff2", "--layout-features=*",
                    "--no-hinting", "--desubroutinize",
                    f"--output-file={OUT / (name + '.woff2')}"], check=True)
    txt.unlink()

def main():
    if not SRC_TTF.exists():
        sys.exit(f"missing {SRC_TTF}")
    OUT.mkdir(parents=True, exist_ok=True)
    site = used_chars()
    common = (gb2312() | {chr(c) for c in range(0x3000, 0x3040)} | {chr(c) for c in range(0xFF00, 0xFFF0)}) - site
    common = {c for c in common if ord(c) > 0x7F}
    for old in OUT.glob("oppo-sans-*.woff2"):
        old.unlink()
    subset(site, "oppo-sans-site")
    chunks = sorted(common)
    slices = [chunks[i:i + 400] for i in range(0, len(chunks), 400)]
    for n, sl in enumerate(slices):
        subset(set(sl), f"oppo-sans-common-{n:02d}")
    face = """@font-face {{
  font-family: "OPPO Sans";
  src: url("/fonts/{file}.woff2") format("woff2");
  font-weight: 100 700;
  font-style: normal;
  font-display: swap;
  unicode-range: {ur};
}}
"""
    css = "/* generated by scripts/subset-fonts.py — do not edit */\n"
    css += face.format(file="oppo-sans-site", ur=ranges(ord(c) for c in site))
    for n, sl in enumerate(slices):
        css += face.format(file=f"oppo-sans-common-{n:02d}", ur=ranges(ord(c) for c in sl))
    css += """@font-face {
  font-family: "Geist";
  src: url("/fonts/Geist-Variable.woff2") format("woff2");
  font-weight: 100 900;
  font-display: swap;
}
@font-face {
  font-family: "Geist Serif";
  src: url("/fonts/GeistSerifVF.woff2") format("woff2");
  font-weight: 400;
  font-display: swap;
}
"""
    CSS.write_text(css, encoding="utf-8")
    for f in sorted(OUT.glob("oppo-sans-*.woff2")):
        print(f.name, f.stat().st_size // 1024, "KB")
    print("site chars:", len(site), "common chars:", len(common))

if __name__ == "__main__":
    main()
