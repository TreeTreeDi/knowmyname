#!/usr/bin/env python3
"""One-off: cut OPPO Sans 4.0 (variable, wght 100-700) into static, committed font files.

Run only when the source TTF changes (needs ../fonts/OPPOSans4.0.ttf and fontTools; the 22 MB TTF is never committed):

1. public/fonts/oppo-sans-common-NN.woff2  GB2312 hanzi + CJK punctuation, ~400 chars per slice,
                                           loaded lazily via unicode-range (src/styles/fonts.css)
2. fonts-src/oppo-sans-source.woff2        the same coverage plus ASCII/Latin-1 in one file; the build-time
                                           script scripts/fonts.mjs cuts the small preloaded subset from it
"""
import pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_TTF = ROOT.parent / "fonts" / "OPPOSans4.0.ttf"
OUT = ROOT / "public" / "fonts"
SRC_OUT = ROOT / "fonts-src"
CSS = ROOT / "src" / "styles" / "fonts.css"

def used_chars():
    chars = set()
    for p in (ROOT / "src").rglob("*"):
        if p.is_file() and p.suffix in {".astro", ".mdx", ".md", ".ts", ".tsx", ".css", ".json"}:
            chars.update(p.read_text(encoding="utf-8"))
    return chars

def gb2312():
    out = set()
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                out.add(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return out

def ranges(cps):
    cps = sorted(cps)
    out, start, prev = [], None, None
    for c in cps:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev)); start = prev = c
    if start is not None:
        out.append((start, prev))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in out)

def subset(chars, path):
    txt = path.with_suffix(".txt")
    txt.write_text("".join(sorted(chars)), encoding="utf-8")
    subprocess.run([sys.executable, "-m", "fontTools.subset", str(SRC_TTF),
                    f"--text-file={txt}", "--flavor=woff2", "--layout-features=*",
                    "--no-hinting", "--desubroutinize", f"--output-file={path}"], check=True)
    txt.unlink()

def main():
    if not SRC_TTF.exists():
        sys.exit(f"missing {SRC_TTF}")
    OUT.mkdir(parents=True, exist_ok=True)
    SRC_OUT.mkdir(parents=True, exist_ok=True)
    cjk = gb2312() | {chr(c) for c in range(0x3000, 0x3040)} | {chr(c) for c in range(0xFF00, 0xFFF0)} | {c for c in used_chars() if ord(c) > 0x7F}
    common = sorted(c for c in cjk if ord(c) > 0x7F)
    for old in OUT.glob("oppo-sans-*.woff2"):
        old.unlink()
    slices = [common[i:i + 400] for i in range(0, len(common), 400)]
    for n, sl in enumerate(slices):
        subset(set(sl), OUT / f"oppo-sans-common-{n:02d}.woff2")
    subset(set(common) | {chr(c) for c in range(0x20, 0x7F)} | {chr(c) for c in range(0xA0, 0x100)} | set("‘’“”–—…·•→←"), SRC_OUT / "oppo-sans-source.woff2")
    face = """@font-face {{
  font-family: "OPPO Sans";
  src: url("/fonts/{file}.woff2") format("woff2");
  font-weight: 100 700;
  font-style: normal;
  font-display: swap;
  unicode-range: {ur};
}}
"""
    css = "/* generated by scripts/subset-fonts.py — do not edit.\n   The preloaded per-site subset is declared later in fonts-site.css (scripts/fonts.mjs), so it is checked first. */\n"
    for n, sl in enumerate(slices):
        css += face.format(file=f"oppo-sans-common-{n:02d}", ur=ranges(ord(c) for c in sl))
    css += """@font-face {
  font-family: "Geist";
  src: url("/fonts/Geist-Variable.woff2") format("woff2");
  font-weight: 100 900;
  font-display: swap;
}
"""
    CSS.write_text(css, encoding="utf-8")
    print(len(slices), "slices;", (SRC_OUT / "oppo-sans-source.woff2").stat().st_size // 1024, "KB source")

if __name__ == "__main__":
    main()
