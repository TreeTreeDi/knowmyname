// Build step: cut the small, preloaded OPPO Sans subset for exactly the characters the site uses.
// Runs before `astro dev` / `astro build` (see package.json), so new posts never need a manual font step.
// Source: fonts-src/oppo-sans-source.woff2 (GB2312 + punctuation + Latin, made once by scripts/subset-fonts.py).
// Anything the subset misses still renders through the lazy unicode-range slices in src/styles/fonts.css.
import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { join, extname } from 'node:path';
import subsetFont from 'subset-font';

const root = new URL('..', import.meta.url).pathname;
const exts = new Set(['.astro', '.md', '.mdx', '.ts', '.tsx', '.json']);

async function walk(dir, out = []) {
  for (const name of await readdir(dir)) {
    const p = join(dir, name);
    if ((await stat(p)).isDirectory()) await walk(p, out);
    else if (exts.has(extname(p))) out.push(p);
  }
  return out;
}

const chars = new Set();
for (const file of await walk(join(root, 'src'))) for (const ch of await readFile(file, 'utf8')) if (ch.codePointAt(0) > 0x7f) chars.add(ch);

const text = [...chars].sort().join('');
const source = await readFile(join(root, 'fonts-src/oppo-sans-source.woff2'));
const woff2 = await subsetFont(source, text, { targetFormat: 'woff2', variationAxes: { wght: { min: 400, max: 600 } } });
await writeFile(join(root, 'public/fonts/oppo-sans-site.woff2'), woff2);

const cps = [...chars].map((c) => c.codePointAt(0)).sort((a, b) => a - b);
const ranges = [];
for (const c of cps) {
  const last = ranges.at(-1);
  if (last && c === last[1] + 1) last[1] = c;
  else ranges.push([c, c]);
}
const ur = ranges.map(([a, b]) => (a === b ? `U+${a.toString(16).toUpperCase()}` : `U+${a.toString(16).toUpperCase()}-${b.toString(16).toUpperCase()}`)).join(',');
await writeFile(
  join(root, 'src/styles/fonts-site.css'),
  `/* generated by scripts/fonts.mjs at build time — do not edit */\n@font-face {\n  font-family: "OPPO Sans";\n  src: url("/fonts/oppo-sans-site.woff2") format("woff2");\n  font-weight: 400 600;\n  font-style: normal;\n  font-display: swap;\n  unicode-range: ${ur};\n}\n`,
);
console.log(`[fonts] ${chars.size} chars → oppo-sans-site.woff2 ${(woff2.length / 1024).toFixed(0)} KB`);
